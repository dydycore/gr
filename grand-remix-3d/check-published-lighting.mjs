import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import publicLighting from './published-lighting.json' with {type:'json'};
import {mergeSceneCatalogue,keepLocalSceneChanges,keepLocalPresetChanges,replaceLocalScene,uniqueSceneName,migratePromotedLighting} from './published-lighting-state.mjs';
const expectedIds=['arrival','opening','dream','red_alert','warm','pinky','dj','hiphop'];
assert.equal(publicLighting.format,'grand-remix-published-lighting');
assert.equal(publicLighting.version,1);
assert.equal(publicLighting.geometryId,'294317811a38');
assert.deepEqual(Object.keys(publicLighting.presetOverrides).sort(),expectedIds.sort());
assert.deepEqual(publicLighting.scenes,[],'Promoted scenes occur only in the main ambience catalogue');
assert.equal(publicLighting.catalogueVersion,2);
assert.equal(publicLighting.holdDuration,30);
for(const scene of publicLighting.scenes){
 assert.equal(scene.duration,30);
 assert.equal(scene.view.camera.length,3);
 assert.equal(scene.view.target.length,3);
}
for(const preset of Object.values(publicLighting.presetOverrides)){
 assert.equal(preset.duration,30);
 assert.ok(preset.prefs&&preset.colors&&preset.timelines);
}
assert.equal(publicLighting.presetOverrides.dream.fog.rate,.06);
assert.equal(publicLighting.presetOverrides.red_alert.timelines.SL1.steps.filter(s=>s.flashHz===8).length,4);
assert.equal(publicLighting.presetOverrides.hiphop.fog.rate,.07);
for(const p of Object.values(publicLighting.presetOverrides))assert.ok(p.fog.rate>=0&&p.fog.rate<=.07,'All published fog presets capped at 7%');
const published=publicLighting.migration.promotedScenes.map(source=>{
 const p=publicLighting.presetOverrides[source.presetId];
 return {name:source.name,duration:p.duration,prefs:p.prefs,colors:p.colors,timelines:p.timelines,view:source.previousView};
});
for(const [id,hash] of Object.entries({pinky:'2e7e71e730377ad48e307f489c944b4f33af326c732b84ec476259b5084133f7',opening:'8f7985be47aea0e987b2e324cbe892cc7b71f9bc599a5ea8971b821cf8bb5461'})){
 const p=publicLighting.presetOverrides[id];
 assert.equal(createHash('sha256').update(JSON.stringify({prefs:p.prefs,colors:p.colors,timelines:p.timelines})).digest('hex'),hash,id+': original user light settings unchanged');
 assert.equal(p.videoMode,id);assert.equal(p.view.ambience,id);assert.equal(p.view.videoMode,id);
}
const legacy={scenes:structuredClone(published),presetOverrides:structuredClone(publicLighting.migration.previousPresetOverrides)};
const migrated=migratePromotedLighting(legacy,publicLighting);
assert.deepEqual(migrated.scenes,[],'Unchanged legacy shared copies disappear');assert.deepEqual(migrated.presetOverrides,{},'An unchanged old opening cache must not hide the promoted opening');
const localEdit=structuredClone(legacy);localEdit.scenes[0].prefs['201'].dimmer=37;localEdit.presetOverrides.opening.prefs['201'].dimmer=22;
const migratedEdit=migratePromotedLighting(localEdit,publicLighting);
assert.equal(migratedEdit.scenes.length,0);assert.equal(migratedEdit.presetOverrides.pinky.prefs['201'].dimmer,37);assert.equal(migratedEdit.presetOverrides.pinky.videoMode,'pinky');assert.equal(migratedEdit.presetOverrides.opening.prefs['201'].dimmer,22);assert.equal(migratedEdit.promotedSceneBackups[0].prefs['201'].dimmer,37);
const differentCase=structuredClone(legacy);differentCase.scenes[0].name='  PINKY LOVE  ';assert.deepEqual(migratePromotedLighting(differentCase,publicLighting).scenes,[],'Legacy names match regardless of letter case or outer spaces');
assert.equal(migratePromotedLighting(migratedEdit,publicLighting),migratedEdit,'Migration is idempotent');
assert.equal(migratePromotedLighting({...legacy,catalogueVersion:2},publicLighting).scenes.length,2,'New intentional saves are never discarded as legacy copies');
const duplicated=published.map(x=>structuredClone(x));
assert.deepEqual(keepLocalSceneChanges(published,duplicated),[]);
assert.equal(mergeSceneCatalogue(published,duplicated).length,2);
const edited=structuredClone(published[0]);edited.duration=17;
assert.equal(keepLocalSceneChanges(published,[edited]).length,1);
assert.equal(mergeSceneCatalogue(published,[edited])[0].duration,17);
assert.equal(mergeSceneCatalogue(published,[{...edited,name:'Une nouvelle scène'}]).length,3);
const replaced=replaceLocalScene([{...edited,name:'Autre'}],'Autre',{...edited,name:'Nouveau'});
assert.deepEqual(replaced.map(x=>x.name),['Nouveau']);
assert.deepEqual(keepLocalPresetChanges(publicLighting.presetOverrides,structuredClone(publicLighting.presetOverrides)),{});
const custom=structuredClone(publicLighting.presetOverrides.dream);custom.fog.rate=.55;
assert.deepEqual(Object.keys(keepLocalPresetChanges(publicLighting.presetOverrides,{dream:custom})),['dream']);
const originalCatalogue=JSON.stringify(published);
const firstCopy={...edited,name:uniqueSceneName(edited.name,published)};
const withCopy=mergeSceneCatalogue(published,[firstCopy]);
assert.equal(firstCopy.name,edited.name+' (2)');
assert.equal(withCopy.length,3,'Save As preserves the original shared scene');
assert.deepEqual(withCopy[0],published[0]);
const secondCopy={...edited,name:uniqueSceneName(edited.name,withCopy)};
assert.equal(secondCopy.name,edited.name+' (3)');
assert.equal(mergeSceneCatalogue(published,[firstCopy,secondCopy]).length,4);
const longName='a'.repeat(70);
assert.equal(uniqueSceneName(longName,[{name:longName}]),'a'.repeat(66)+' (2)');
assert.equal(uniqueSceneName('   ',[]),'Mon ambiance');
const sharedIndex=0,renamed={...edited,name:uniqueSceneName('Scène renommée',published.filter((_,i)=>i!==sharedIndex))};
let local=replaceLocalScene([],published[sharedIndex].name,renamed);
let catalogue=mergeSceneCatalogue(published,local);
const renamedIndex=catalogue.indexOf(renamed);
assert.equal(renamedIndex,2,'Renaming a shared scene appends a personal scene and changes its index');
const savedAgain={...renamed,duration:21};
local=replaceLocalScene(local,catalogue[renamedIndex].name,savedAgain);
catalogue=mergeSceneCatalogue(published,local);
assert.deepEqual(catalogue.slice(0,2),published,'A subsequent Save must use the new index and preserve both shared scenes');
assert.equal(catalogue[renamedIndex].duration,21);
assert.equal(uniqueSceneName(published[1].name,catalogue.filter((_,i)=>i!==renamedIndex)),published[1].name+' (2)','Rename collision does not overwrite another scene');
assert.equal(JSON.stringify(published),originalCatalogue,'Public data is never mutated');
console.log('PASS : 8 ambiances principales, Pinky et Ouverture intactes, migration sans doublons, copies sans écrasement et modifications locales préservées.');
